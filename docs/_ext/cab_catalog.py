"""Sphinx extension: generate the dosho cab/image catalog at build time.

The catalog page (``reference/cabs.rst``) is written from the *live*
``dosho.registry`` + the image manifest on the ``builder-inited`` event, so it
can never drift from the code: every registered cab appears with its resolved
container image (KEY, version, provenance) and its input/output schema, pulled
straight from the same objects the pipeline runs. There is no hand-maintained
list to keep in sync.

Binary definitions expose exact declared dtype labels through Dosho's public
schema description. Marked Python functions use its shared signature helpers.
Neither path imports or constructs a Shinobi execution object.
"""

from __future__ import annotations

import warnings
from pathlib import Path
from typing import Any

from dosho._inspection import _fields, _schema_obj, _summary, _type_name as _type_name


def _rst_cell(text: str) -> str:
    """Neutralise the RST inline-markup characters that would break a table
    cell, so arbitrary field descriptions render literally."""
    if not text:
        return "\\-"
    for a, b in (("\\", "\\\\"), ("*", "\\*"), ("`", "\\`"), ("|", "\\|"), ("_", "\\_")):
        text = text.replace(a, b)
    return " ".join(text.split())


def _image_index() -> dict[str, dict[str, str]]:
    """resolved image ref -> {key, version, source, kind}, from the manifest."""
    from dosho import images

    idx: dict[str, dict[str, str]] = {}
    for key, entry in images.manifest["images"].items():
        ref = getattr(images, key, None)
        if not ref:
            continue
        build = entry.get("build")
        version = (
            build["version"] if build else (ref.rsplit(":", 1)[-1] if ":" in ref else "external")
        )
        idx[ref] = {
            "key": key,
            "version": str(version),
            "source": entry.get("source", ""),
            "kind": "build" if build else "ref",
        }
    return idx


def _field_table(model: Any, with_default: bool) -> list[str]:
    """A list-table of a pydantic model's fields (Field/Type[/Default]/Description)."""
    fields = model if isinstance(model, dict) else getattr(model, "model_fields", {})
    if not fields:
        return ["*(none)*", ""]
    widths = "25 20 15 40" if with_default else "30 25 45"
    lines = [".. list-table::", "   :header-rows: 1", f"   :widths: {widths}", ""]
    header = ["Field", "Type"] + (["Default"] if with_default else []) + ["Description"]
    lines.append("   * - " + header[0])
    lines += [f"     - {h}" for h in header[1:]]
    for name, field in _fields(model):
        row = [f"``{name}``", f"``{field['dtype']}``"]
        if with_default:
            row.append("*required*" if field["required"] else f"``{field['default']!r}``")
        constraints = field["constraints"] if isinstance(model, dict) else []
        description = " ".join([field["description"], *constraints]).strip()
        row.append(_rst_cell(description))
        lines.append(f"   * - {row[0]}")
        lines += [f"     - {c}" for c in row[1:]]
    lines.append("")
    return lines


def _generate(app: Any) -> None:
    from dosho import registry

    img_index = _image_index()
    lines = [
        ".. This page is generated by docs/_ext/cab_catalog.py -- do not edit by hand.",
        "",
        "Cab catalog",
        "===========",
        "",
        "Every tool registered in dosho, with the container image it resolves to and",
        "its input/output schema. Generated from the live registry and image manifest",
        "at build time, so it stays in lockstep with the code.",
        "",
    ]

    for name in sorted(registry.list_cabs()):
        # `registry.get` warns for an experimental cab, which is right for a
        # caller about to *run* one and pure noise for a catalog that renders
        # every cab in the repo -- the marker reaches the page anyway, via the
        # `EXPERIMENTAL:` prefix `define_cab` puts on the cab's own `info`.
        with warnings.catch_warnings():
            warnings.simplefilter("ignore", UserWarning)
            obj = _schema_obj(registry.get(name))
        ref = getattr(obj, "image", None)
        meta = img_index.get(ref)

        lines += [name, "-" * len(name), ""]
        summary = _summary(getattr(obj, "info", None))
        if summary:
            lines += [summary, ""]

        command = getattr(obj, "command", None)
        if command:
            lines.append(f":Command: ``{command}``")
        if ref:
            if meta:
                image_line = (
                    f":Image: ``{ref}`` (``{meta['key']}`` {meta['version']}, {meta['kind']})"
                )
                lines.append(image_line)
                if meta["source"]:
                    lines.append(f":Source: {meta['source']}")
            else:
                lines.append(f":Image: ``{ref}``")
        lines.append("")

        lines.append("**Inputs**")
        lines.append("")
        lines += _field_table(
            getattr(obj, "inputs", getattr(obj, "inputs_model", None)), with_default=True
        )
        lines.append("**Outputs**")
        lines.append("")
        lines += _field_table(
            getattr(obj, "outputs", getattr(obj, "outputs_model", None)), with_default=False
        )

    out = Path(app.srcdir) / "reference" / "cabs.rst"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n")


def setup(app: Any) -> dict[str, Any]:
    app.connect("builder-inited", _generate)
    return {"version": "0.1", "parallel_read_safe": True, "parallel_write_safe": True}


def main() -> int:
    """Standalone regeneration, for the pre-commit hook (and anyone who wants
    the catalog refreshed without a full sphinx build): rewrite
    ``docs/reference/cabs.rst`` in place from the live registry. Exits 1 when
    that changed the file -- the pre-commit convention for "I fixed it, stage
    the result and commit again" -- and 0 when it was already fresh.
    """
    import types

    docs_dir = Path(__file__).resolve().parents[1]
    out = docs_dir / "reference" / "cabs.rst"
    before = out.read_text() if out.exists() else None
    _generate(types.SimpleNamespace(srcdir=str(docs_dir)))
    if out.read_text() != before:
        print(f"{out}: cab catalog was stale -- regenerated; stage it and commit again")
        return 1
    print("cab catalog is up to date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
